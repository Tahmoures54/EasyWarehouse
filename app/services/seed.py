def seed_if_empty(db: "DB") -> int:
    """اگر جدول کالا خالی باشد، اقلام پیش‌فرض را درج می‌کند."""
    from app.services.product_service import ProductService

    ps = ProductService(db)
    if ps.count() > 0:
        return 0
    n = 0
    for name, unit, mn, cat in SEED_PRODUCTS:
        try:
            ps.add(name, unit, mn, cat)
            n += 1
        except Exception:
            continue
    return n
